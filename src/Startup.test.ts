import { afterEach, expect, it, vi } from "vitest";
const mocks = vi.hoisted(() => ({ clear: vi.fn(), textures: vi.fn(), init: vi.fn(), status: {textContent: "", removeAttribute: vi.fn()} }));
vi.mock("./MobileLayout", () => ({setupMobileLayout: vi.fn()}));
vi.mock("./DensityHistory", () => ({trackDensityAsync: vi.fn()}));
vi.mock("./MineProbability", () => ({prepareProbability: vi.fn()}));
vi.mock("./ScorePlot", () => ({ScorePlot: vi.fn()}));
vi.mock("./Textures", () => ({loadTextures: mocks.textures}));
vi.mock("./FieldPersistence", () => ({FieldPersistence: class {
 clearAsync = mocks.clear;
 loadLatest = async () => ({clickScores: [0], getAll: () => [], score: 0, cellData: {numberStorage: {size: 0}}});
}}));
vi.mock("./FieldRenderer", () => ({FieldRenderer: class {prepareCells = async () => {}; init = mocks.init;}}));
afterEach(() => {vi.unstubAllGlobals(); vi.restoreAllMocks();});
it.each(["textures", "init"])("reports %s startup failure through the existing status", async (stage) => {
 vi.resetModules(); mocks.status.textContent = "";
 mocks.textures.mockReset().mockResolvedValue(undefined);
 mocks.init.mockReset().mockResolvedValue(undefined);
 mocks[stage as "textures" | "init"].mockRejectedValue(new Error("startup failure"));
 const removeItem=vi.fn(), reload=vi.fn();
 mocks.clear.mockReset().mockResolvedValue(undefined);
 vi.stubGlobal("window", {localStorage: {removeItem}, location: {reload}});
 vi.stubGlobal("self", {});
 vi.stubGlobal("document", {querySelector: () => mocks.status});
 vi.spyOn(console,"error").mockImplementation(() => {});
 await import("./index");
 await vi.waitFor(() => expect(mocks.status.textContent).toContain("Loading failed"));
 await (mocks.status as any).onclick();
 expect(mocks.clear).toHaveBeenCalledWith("defaultSavedFieldv3");
 expect(removeItem).toHaveBeenCalledWith("savedCamerTransform");
 expect(removeItem).toHaveBeenCalledTimes(1);
 expect(reload).toHaveBeenCalledOnce();
});
